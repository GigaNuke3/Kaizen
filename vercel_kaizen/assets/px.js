/** Inline SVG for a sprite; horizontal runs of one color merge into one <rect> */
function px(name, size = null, cls = '') {
  const layers = PX_SPRITES[name]
  if (!layers) return ''
  const groups = layers.map(({ anim, delay, rows }) => {
    let rects = ''
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length;) {
        const ch = row[x]
        let end = x + 1
        while (row[end] === ch) end++
        if (ch !== '.') rects += `<rect x="${x}" y="${y}" width="${end - x}" height="1" fill="${PX_PALETTE[ch]}"/>`
        x = end
      }
    })
    const style = delay ? ` style="animation-delay:${delay}s"` : ''
    return `<g${anim ? ` class="px-a-${anim}"` : ''}${style}>${rects}</g>`
  }).join('')
  const dim = size ? ` style="width:${size}px;height:${size}px"` : ''
  return `<svg class="px px-${name}${cls ? ' ' + cls : ''}"${dim} viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">${groups}</svg>`
}

if (typeof module !== 'undefined') module.exports = { px, PX_SPRITES, PX_PALETTE }
